#!/usr/bin/env python3
"""Generate Android and Compose tokens from the vendored Base16 Oxocarbon YAML."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
source = root / "design/base16-oxocarbon-dark.yaml"
tokens = dict(re.findall(r'^base([0-9A-Fa-f]{2}):\s*"([0-9a-fA-F]{6})"', source.read_text(), re.M))
tokens = {key.upper(): value.upper() for key, value in tokens.items()}
expected = [f"{n:02X}" for n in range(16)]
if set(tokens) != set(expected):
    raise SystemExit("Expected all 16 canonical Base16 colours")
header = "// Generated by scripts/sync_oxocarbon.py; edit the source YAML, not this file.\n"
kotlin = header + "package com.nazcarbon.music.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\ninternal object Oxocarbon {\n"
kotlin += "".join(f"    val Base{key} = Color(0xFF{tokens[key]})\n" for key in expected) + "}\n"
xml = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/sync_oxocarbon.py from the canonical Base16 YAML. -->\n<resources>\n'
xml += "".join(f'    <color name="oxocarbon_base{key.lower()}">#{tokens[key]}</color>\n' for key in expected) + "</resources>\n"
outputs = {
    root / "app/src/main/java/com/nazcarbon/music/ui/theme/Oxocarbon.kt": kotlin,
    root / "app/src/main/res/values/oxocarbon.xml": xml,
}
for path, content in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Palette drift: {path.relative_to(root)}")
    else:
        path.write_text(content)
print("All 16 Base16 colours agree across source, Compose and Android resources.")
